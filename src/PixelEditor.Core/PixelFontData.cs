namespace PixelEditor.Core;

/// <summary>
/// The hand-drawn glyph bitmaps. A glyph is a string of rows separated by '/', '#' is ink and '.' is empty.
/// Rows may be given for the cap height only (the descender rows are added empty), or for the whole line box.
/// To add a glyph: add one line to the right Build method; the font tests check the cell size of every glyph.
/// </summary>
internal static class PixelFontData
{
    private sealed class Table(int width, int ascent, int height, int xHeight)
    {
        public readonly Dictionary<char, string[]> D = new();

        private void Put(char c, IEnumerable<string> top, int blankTop)
        {
            var rows = new List<string>();
            for (int i = 0; i < blankTop; i++) rows.Add(new string('.', width));
            rows.AddRange(top);
            if (rows.Count > height) throw new InvalidOperationException($"glyph '{c}' is too tall");
            while (rows.Count < height) rows.Add(new string('.', width));
            foreach (var r in rows) if (r.Length != width) throw new InvalidOperationException($"glyph '{c}': row '{r}' is not {width} wide");
            D[c] = rows.ToArray();
        }

        /// <summary>Caps, digits, punctuation, ascenders: rows from the top (the cap height, or the whole line box).</summary>
        public void G(char c, string rows)
        {
            var r = rows.Split('/');
            if (r.Length != ascent && r.Length != height) throw new InvalidOperationException($"glyph '{c}' has {r.Length} rows");
            Put(c, r, 0);
        }

        /// <summary>A letter of x-height rows (or fewer), sitting on the baseline.</summary>
        public void Low(char c, string rows)
        {
            var r = rows.Split('/');
            Put(c, r, ascent - r.Length);
        }

        /// <summary>A letter whose body is x-height rows and whose tail goes below the baseline.</summary>
        public void Desc(char c, string rows) => Put(c, rows.Split('/'), ascent - xHeight);
    }

